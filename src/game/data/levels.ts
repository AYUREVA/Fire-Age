// =====================================================================
//  Уровни каменного века. Это данные для гейм-дизайнера, как settings.ts:
//  уровень включает механики данными, а не отдельным кодом (раздел 9 плана,
//  правило 4). Чего нет в уровне (волков, точки покупки) — того нет в игре.
//  Время — в миллисекундах.
// =====================================================================

// Один уровень.
export type LevelData = {
  // Название: на табличке старта и на карте уровней.
  name: string;
  // Сколько суток в уровне. Рассвет после последней ночи — победа.
  dayCount: number;
  // Сколько мс длятся день и ночь. Ночь — не дольше NIGHT_MAX_DURATION (settings.ts).
  day: number;
  night: number;
  // Волки. Нет поля — волков на уровне нет.
  // day / night — сколько волков может быть на поле днём и ночью (фаза 2),
  // firstDelay — через сколько мс после начала выходит первый волк.
  wolves?: { day: number; night: number; firstDelay: number };
  // Путники: когда приходит первый и как часто следующие (мс), если в очереди есть место.
  // firstOrder — сколько кусков просит первый путник (нет поля — сколько угодно, как все).
  travelers: { firstDelay: number; interval: number; firstOrder?: number };
  // Точка покупки частокола: цена в клыках и где стоит. Нет поля — частокол не продаётся.
  fence?: { price: number; spot: Point };
  // Точка покупки оружия: где стоит. Цены оружия — в data/upgrades.ts (WEAPONS).
  weapons?: { spot: Point };
  // Хижины: цена одной и места. Хижина встаёт на место своей точки покупки.
  huts?: { price: number; spots: Point[] };
  // Прорубь и малый костёр с рыбой (с 0.8). Нет поля — рыбы на уровне нет.
  // fishShare — доля путников, которые просят рыбу, а не мясо (0.4 — примерно каждый второй-третий).
  fishing?: { fishShare: number };
  // Точки найма помощников (с 0.8): для каждой роли — цена в клыках и где стоит точка.
  // Помощник появляется на месте своей точки. Нет роли — её не нанять. Что умеют роли — data/upgrades.ts.
  helpers?: Partial<Record<HelperRole, { price: number; spot: Point }>>;
  // Третья звезда: накормить не меньше стольких путников.
  starFed: number;
  // Есть ли обучение стрелками-подсказками.
  hasTutorial: boolean;
};

